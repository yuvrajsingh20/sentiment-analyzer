/* ── stage 2: validate input ─────────────────────────────────────────────── */

const validateCode = `${GENERATED_BANNER}
//
// Stage 2 — Validate input.
// Reject a malformed request here so a bad payload never reaches the model and
// never costs a token.

const MAX_TRANSCRIPT_CHARS = 400000;

const body = $input.first().json.body ?? {};
const fail = (status, error) => [{ json: { ok: false, status, error } }];

const transcript = typeof body.transcript === 'string' ? body.transcript : '';
const turnCount = Number(body.turnCount);
const speakerRoles = Array.isArray(body.speakerRoles) ? body.speakerRoles : [];
const fileName =
  typeof body.fileName === 'string' && body.fileName.trim()
    ? body.fileName.trim()
    : 'transcript.txt';
const retryFeedback =
  typeof body.retryFeedback === 'string' ? body.retryFeedback : '';

if (!transcript.trim()) {
  return fail(400, 'Request is missing a non-empty "transcript".');
}
if (!Number.isFinite(turnCount) || turnCount < 1) {
  return fail(400, 'Request is missing a positive integer "turnCount".');
}
if (transcript.length > MAX_TRANSCRIPT_CHARS) {
  return fail(413, 'Transcript exceeds the 400 KB limit.');
}
for (const entry of speakerRoles) {
  if (!entry || typeof entry.speaker !== 'string' || typeof entry.role !== 'string') {
    return fail(400, '"speakerRoles" entries must be { speaker, role } objects.');
  }
}

return [
  { json: { ok: true, fileName, turnCount, speakerRoles, transcript, retryFeedback } },
];
`;

/* ── stage 3: normalise & parse ──────────────────────────────────────────── */

const normalizeCode = `${GENERATED_BANNER}
//
// Stage 3 — Normalise and parse the conversation.
// The app sends the transcript already segmented as "[n] Speaker: text", one
// turn per line. This stage rebuilds that into a structured turn array so the
// later evidence-verification stage has something to match quotes against —
// and so a mismatch between the claimed turnCount and the actual line count is
// caught before the model is called.

const input = $input.first().json;

const normalised = input.transcript
  .replace(/\\r\\n?/g, '\\n')
  .replace(/\\u00A0/g, ' ')
  .replace(/[\\u0000-\\u0008\\u000B\\u000C\\u000E-\\u001F\\u007F]/g, '');

const turns = [];
for (const line of normalised.split('\\n')) {
  const match = /^\\s*\\[(\\d+)\\]\\s*([^:]{1,64}?):\\s*([\\s\\S]*)$/.exec(line);
  if (!match) continue;
  turns.push({
    index: Number(match[1]),
    speaker: match[2].trim(),
    text: match[3].trim(),
  });
}

if (turns.length === 0) {
  return [
    {
      json: {
        ok: false,
        status: 422,
        error: 'No "[n] Speaker: text" turns could be parsed from the transcript.',
      },
    },
  ];
}

if (turns.length !== input.turnCount) {
  // Not fatal — trust what actually parsed, and report the discrepancy.
  input.turnCountMismatch = { declared: input.turnCount, parsed: turns.length };
}

return [
  {
    json: {
      ok: true,
      fileName: input.fileName,
      turnCount: turns.length,
      declaredTurnCount: input.turnCount,
      turnCountMismatch: input.turnCountMismatch ?? null,
      speakerRoles: input.speakerRoles,
      transcript: normalised,
      retryFeedback: input.retryFeedback,
      turns,
    },
  },
];
`;

/* ── stage 4: build the Gemini request ───────────────────────────────────── */

const buildRequestCode = `${GENERATED_BANNER}
//
// Stage 4 — Build the Gemini request.
// SYSTEM_PROMPT and OUTPUT_JSON_SCHEMA below are inlined copies of
// src/contract/analysis-contract.mjs. Nothing about the model's instructions
// is decided in n8n; this node only assembles them. The API key is not here —
// it lives in the n8n Header Auth credential on the next node.

const SYSTEM_PROMPT = ${JSON.stringify(SYSTEM_PROMPT)};
const OUTPUT_JSON_SCHEMA = ${JSON.stringify(OUTPUT_JSON_SCHEMA)};
const MODEL = $env.GEMINI_MODEL || ${JSON.stringify(DEFAULT_MODEL)};

const input = $input.first().json;

const roster = input.speakerRoles
  .map((s) => \`- "\${s.speaker}" → \${s.role}\`)
  .join('\\n');

const retry = input.retryFeedback
  ? '\\n\\nThe previous attempt at this analysis failed automated verification:\\n' +
    input.retryFeedback +
    '\\nFix those specific problems. Quotes must be exact substrings of the turn they cite.\\n'
  : '';

const userPrompt = [
  'Analyse the following call transcript.',
  '',
  \`File: \${input.fileName}\`,
  \`Turns: \${input.turnCount}\`,
  '',
  'Speaker roles (detected by the transcript parser — trust these unless the transcript clearly contradicts them):',
  roster,
  '',
  \`Each turn is prefixed with its index in square brackets. Return exactly \${input.turnCount} entries in \\\`utterances\\\`, with indices 0 through \${input.turnCount - 1}.\`,
  '',
  'Evidence quotes must be exact substrings of the turn they cite, excluding the \`[n] Speaker:\` prefix.' + retry,
  '',
  '--- TRANSCRIPT START ---',
  input.transcript,
  '--- TRANSCRIPT END ---',
].join('\\n');

return [
  {
    json: {
      ok: true,
      context: input,
      model: MODEL,
      geminiUrl:
        'https://generativelanguage.googleapis.com/v1beta/models/' +
        MODEL +
        ':generateContent',
      geminiRequest: {
        systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] },
        contents: [{ role: 'user', parts: [{ text: userPrompt }] }],
        generationConfig: {
          temperature: 0.2,
          maxOutputTokens: 32768,
          responseMimeType: 'application/json',
          responseJsonSchema: OUTPUT_JSON_SCHEMA,
        },
      },
    },
  },
];
`;

/* ── stage 6: parse & schema-validate ────────────────────────────────────── */

const parseResponseCode = `${GENERATED_BANNER}
//
// Stage 6 — Parse and schema-validate.
// Unwrap the Gemini generateContent response and check the analysis against
// the contract's required shape before anything downstream touches it.

const response = $input.first().json;
const built = $('Build Gemini request').first().json;
const context = built.context;

const fail = (status, error, detail) => [
  { json: { ok: false, status, error, detail } },
];

if (response.error) {
  const code = Number(response.error.code);
  const msg = String(response.error.message || '');
  if (code === 429 || /RESOURCE_EXHAUSTED/i.test(msg)) {
    return fail(429, 'Gemini is rate limited. Wait a moment and try again.');
  }
  if (code === 503 || /high demand|UNAVAILABLE|overloaded/i.test(msg)) {
    return fail(503, 'Gemini is busy right now. Wait a few seconds and try again.');
  }
  const status = code === 403 || code === 401 ? 502 : 502;
  return fail(status, 'The Gemini API returned an error.', msg.slice(0, 280));
}

const candidate = (response.candidates ?? [])[0];
if (!candidate) {
  return fail(502, 'The Gemini API returned no candidates.');
}

const finish = candidate.finishReason || candidate.finish_reason;
if (finish === 'MAX_TOKENS') {
  return fail(
    413,
    'The response was truncated before the analysis was complete. Try a shorter transcript.',
  );
}
if (finish === 'SAFETY' || finish === 'RECITATION' || finish === 'PROHIBITED_CONTENT') {
  return fail(
    422,
    'The model declined to analyse this transcript.',
    finish,
  );
}

const text = (candidate.content?.parts ?? [])
  .map((p) => (typeof p.text === 'string' ? p.text : ''))
  .join('');
if (!text.trim()) {
  return fail(502, 'The model returned no analysis payload.');
}

let analysis;
try {
  analysis = JSON.parse(text);
} catch (error) {
  return fail(502, 'The model returned malformed JSON.', String(error));
}

const REQUIRED_TOP_LEVEL = ${JSON.stringify(OUTPUT_JSON_SCHEMA.required)};
const missing = REQUIRED_TOP_LEVEL.filter((key) => analysis[key] === undefined);
if (missing.length > 0) {
  return fail(502, 'The analysis is missing required fields.', missing.join(', '));
}
if (!Array.isArray(analysis.utterances) || analysis.utterances.length === 0) {
  return fail(502, 'The analysis contains no per-turn labels.');
}
for (const group of ['customer', 'agent', 'conversation']) {
  if (!analysis.kpis || typeof analysis.kpis[group] !== 'object') {
    return fail(502, \`The analysis is missing the "\${group}" KPI group.\`);
  }
}

const usage = response.usageMetadata ?? response.usage ?? null;

return [
  {
    json: {
      ok: true,
      analysis,
      context,
      model: response.modelVersion || built.model,
      stopReason: finish || 'STOP',
      usage,
    },
  },
];
`;

/* ── stage 7: verify evidence ────────────────────────────────────────────── */

const verifyEvidenceCode = `${GENERATED_BANNER}
//
// Stage 7 — Verify evidence (the hallucination guard).
// Every quote the model cited is matched back against the turn it claims to
// come from. A quote that cannot be found is a fabrication and is recorded as
// one. The matcher below is src/contract/evidence-check.mjs verbatim, so this
// stage and the app's quality gate cannot disagree.

/* ── begin shared: src/contract/evidence-check.mjs ────────────────────── */
${EVIDENCE_CHECK_SOURCE}
/* ── end shared ───────────────────────────────────────────────────────── */

const input = $input.first().json;
const analysis = input.analysis;
const turns = input.context.turns;
const index = indexTranscript(turns);

let quotesTotal = 0;
let quotesGrounded = 0;
let quotesMoved = 0;
let quotesFuzzy = 0;
const fabricated = [];

const check = (list) =>
  (Array.isArray(list) ? list : []).map((e) => {
    const verdict = verifyQuote(e.quote, e.turnIndex, index);
    if (verdict.kind !== 'empty') quotesTotal += 1;
    if (verdict.verified) {
      quotesGrounded += 1;
      if (verdict.kind === 'moved') quotesMoved += 1;
      if (verdict.kind === 'fuzzy') quotesFuzzy += 1;
    } else if (verdict.kind === 'missing') {
      fabricated.push(e.quote);
    }
    const out = { ...e, verified: verdict.verified };
    if (verdict.matchedTurnIndex !== null && verdict.matchedTurnIndex !== e.turnIndex) {
      out.matchedTurnIndex = verdict.matchedTurnIndex;
    }
    return out;
  });

// Walk every place evidence can appear.
if (analysis.overall) analysis.overall.evidence = check(analysis.overall.evidence);
for (const e of analysis.emotions ?? []) e.evidence = check(e.evidence);
for (const a of analysis.actionItems ?? []) a.evidence = check(a.evidence);
for (const c of analysis.coaching ?? []) c.evidence = check(c.evidence);

for (const group of ['customer', 'agent', 'conversation']) {
  const kpis = analysis.kpis?.[group] ?? {};
  for (const [key, claim] of Object.entries(kpis)) {
    if (key === 'topics' || key === 'complianceChecks') continue;
    if (claim && typeof claim === 'object') claim.evidence = check(claim.evidence);
  }
}
for (const c of analysis.kpis?.conversation?.complianceChecks ?? []) {
  c.evidence = check(c.evidence);
}

let momentQuotesBad = 0;
for (const m of analysis.keyMoments ?? []) {
  if (!m.quote) continue;
  const verdict = verifyQuote(m.quote, m.utteranceIndex, index);
  if (verdict.kind !== 'empty') quotesTotal += 1;
  if (verdict.verified) quotesGrounded += 1;
  else if (verdict.kind === 'missing') {
    momentQuotesBad += 1;
    fabricated.push(m.quote);
  }
}

return [
  {
    json: {
      ...input,
      analysis,
      evidenceStats: {
        quotesTotal,
        quotesGrounded,
        quotesMoved,
        quotesFuzzy,
        momentQuotesBad,
        fabricated,
      },
    },
  },
];
`;

/* ── stage 8: KPI engine ─────────────────────────────────────────────────── */

const kpiEngineCode = `${GENERATED_BANNER}
//
// Stage 8 — KPI engine.
// Deterministic arithmetic over the parsed turns. Talk ratio, word counts and
// question counts are exactly the numbers an LLM is worst at, so they are
// computed here rather than trusted from the model. The quality gate then
// flags answered KPI claims that cite no evidence.

const input = $input.first().json;
const turns = input.context.turns ?? [];
const roles = new Map(
  (input.context.speakerRoles ?? []).map((s) => [s.speaker.toLowerCase(), s.role]),
);

const wordCount = (text) =>
  (String(text).match(/[\\p{L}\\p{N}][\\p{L}\\p{N}'’-]*/gu) ?? []).length;

const countQuestions = (text) => {
  const explicit = (String(text).match(/\\?/g) ?? []).length;
  if (explicit > 0) return explicit;
  return /^\\s*(who|what|when|where|why|how|can|could|would|will|do|does|did|is|are|was|were|have|has|may|might|shall|should)\\b/i.test(
    text,
  )
    ? 1
    : 0;
};

let agentWords = 0;
let customerWords = 0;
let totalWords = 0;
let questions = 0;
for (const t of turns) {
  const words = wordCount(t.text);
  totalWords += words;
  questions += countQuestions(t.text);
  const role = roles.get(String(t.speaker).toLowerCase());
  if (role === 'agent') agentWords += words;
  else if (role === 'customer') customerWords += words;
}

const pair = agentWords + customerWords;
const round = (n) => Math.round(n * 1000) / 1000;

const claims = [];
for (const group of ['customer', 'agent', 'conversation']) {
  for (const [key, claim] of Object.entries(input.analysis?.kpis?.[group] ?? {})) {
    if (key === 'topics' || key === 'complianceChecks') continue;
    if (claim && typeof claim === 'object') claims.push({ group, key, claim });
  }
}

const answered = claims.filter(
  (c) => c.claim.status === 'ok' && c.claim.value !== null && c.claim.value !== undefined,
);
const answeredWithoutEvidence = answered.filter(
  (c) => !Array.isArray(c.claim.evidence) || c.claim.evidence.length === 0,
).map((c) => c.group + '.' + c.key);

const computed = {
  turns: turns.length,
  words: totalWords,
  questions,
  talkRatio: {
    agent: pair > 0 ? round(agentWords / pair) : 0,
    customer: pair > 0 ? round(customerWords / pair) : 0,
  },
  answeredKpis: answered.length,
  abstainedKpis: claims.length - answered.length,
  answeredWithoutEvidence,
};

return [{ json: { ...input, computed } }];
`;

/* ── stage 9: quality gate ───────────────────────────────────────────────── */

const qualityGateCode = `${GENERATED_BANNER}
//
// Stage 9 — Quality gate.
// Turn the raw counts into coverage / grounding / support metrics and a verdict.
// Mirrors src/lib/verify.ts. The gate reports; it never silently drops an
// analysis, because a reviewer needs to see a bad run as much as a good one.

const TURN_COVERAGE_FAIL = 0.9;
const GROUNDING_FAIL = 0.7;

const input = $input.first().json;
const analysis = input.analysis;
const turns = input.context.turns;
const stats = input.evidenceStats;

const validIndices = new Set(turns.map((t) => t.index));
const labelled = new Set((analysis.utterances ?? []).map((u) => u.index));
const missingTurns = turns.filter((t) => !labelled.has(t.index)).map((t) => t.index);
const phantomTurns = (analysis.utterances ?? [])
  .map((u) => u.index)
  .filter((i) => !validIndices.has(i));

const turnCoverage =
  turns.length === 0 ? 1 : (turns.length - missingTurns.length) / turns.length;

// Flatten every claim across the three KPI groups.
const claims = [];
for (const group of ['customer', 'agent', 'conversation']) {
  for (const [key, claim] of Object.entries(analysis.kpis?.[group] ?? {})) {
    if (key === 'topics' || key === 'complianceChecks') continue;
    if (claim && typeof claim === 'object') claims.push(claim);
  }
}

const answered = claims.filter(
  (c) => c.status === 'ok' && c.value !== null && c.value !== undefined,
);
const abstentions = claims.length - answered.length;
const unsupportedClaims = answered.filter(
  (c) => !Array.isArray(c.evidence) || c.evidence.length === 0,
).length;
const lowConfidenceClaims = answered.filter((c) => Number(c.confidence) < 0.5).length;

const evidenceCoverage =
  answered.length === 0 ? 1 : (answered.length - unsupportedClaims) / answered.length;
const evidenceGrounding =
  stats.quotesTotal === 0 ? 1 : stats.quotesGrounded / stats.quotesTotal;

const issues = [];
const add = (code, severity, message, count) =>
  issues.push({ code, severity, message, count });

if (missingTurns.length > 0)
  add(
    'missing_turn_labels',
    turnCoverage < TURN_COVERAGE_FAIL ? 'error' : 'warn',
    missingTurns.length + ' turn(s) came back unlabelled.',
    missingTurns.length,
  );
if (phantomTurns.length > 0)
  add(
    'phantom_turns',
    'warn',
    phantomTurns.length + ' label(s) referenced turns that do not exist.',
    phantomTurns.length,
  );
if (stats.fabricated.length > 0)
  add(
    'ungrounded_evidence',
    evidenceGrounding < GROUNDING_FAIL ? 'error' : 'warn',
    stats.fabricated.length + ' quote(s) could not be found in the transcript.',
    stats.fabricated.length,
  );
if (unsupportedClaims > 0)
  add(
    'unsupported_claims',
    'warn',
    unsupportedClaims + ' answered claim(s) cite no evidence.',
    unsupportedClaims,
  );
if (stats.momentQuotesBad > 0)
  add(
    'ungrounded_key_moment',
    'warn',
    stats.momentQuotesBad + ' key-moment quote(s) are not verbatim.',
    stats.momentQuotesBad,
  );
if (stats.quotesMoved > 0)
  add(
    'misattributed_quotes',
    'info',
    stats.quotesMoved + ' quote(s) were cited against the wrong turn.',
    stats.quotesMoved,
  );
if (stats.quotesFuzzy > 0)
  add(
    'near_verbatim_quotes',
    'info',
    stats.quotesFuzzy + ' quote(s) matched only after normalisation.',
    stats.quotesFuzzy,
  );
if (abstentions > 0)
  add(
    'abstentions',
    'info',
    abstentions + ' KPI(s) were marked insufficient_evidence rather than guessed.',
    abstentions,
  );
if (lowConfidenceClaims > 0)
  add(
    'low_confidence',
    'info',
    lowConfidenceClaims + ' claim(s) were answered with confidence below 50%.',
    lowConfidenceClaims,
  );

const hasError = issues.some((i) => i.severity === 'error');
const hasWarn = issues.some((i) => i.severity === 'warn');
const round = (n) => Math.round(n * 1000) / 1000;

const quality = {
  verdict: hasError ? 'fail' : hasWarn ? 'warn' : 'pass',
  score: round(
    0.35 * turnCoverage +
      0.35 * evidenceGrounding +
      0.2 * evidenceCoverage +
      0.1 * (phantomTurns.length === 0 ? 1 : 0),
  ),
  attempts: 1,
  checks: {
    schemaValid: true,
    turnCoverage: round(turnCoverage),
    evidenceCoverage: round(evidenceCoverage),
    evidenceGrounding: round(evidenceGrounding),
    unsupportedClaims,
    fabricatedQuotes: stats.fabricated.length,
    abstentions,
    lowConfidenceClaims,
    phantomTurns: phantomTurns.length,
  },
  issues,
};

return [{ json: { ok: true, analysis, quality, context: input.context, model: input.model, usage: input.usage, missingTurns, phantomTurns, computed: input.computed ?? null } }];
`;

