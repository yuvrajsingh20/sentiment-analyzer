const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "n8n", "sentiment-analyzer.workflow.json");

/**
 * Inline the shared evidence checker into a Code node.
 *
 * n8n Code nodes have no module system, so the source is read from disk and
 * its `export` keywords stripped. Reading the real file (rather than pasting a
 * copy) is what keeps the workflow's hallucination guard identical to the
 * app's — `npm run verify:workflow` asserts it byte for byte.
 */
function inlineSharedModule(relativePath) {
  const source = readFileSync(join(here, "..", relativePath), "utf8");
  return source
    .replace(/^export (const|function) /gm, "$1 ")
    .replace(/^export \{[^}]*\};?$/gm, "")
    .trim();
}

