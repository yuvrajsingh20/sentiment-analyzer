/**
 * Generates n8n/sentiment-analyzer.workflow.json.
 *
 * The workflow is generated, not hand-written, so that the system prompt, the
 * output JSON Schema and the evidence-matching rules inside it are literally
 * the same values the app uses — imported from src/contract/, not retyped.
 * Change the contract, re-run this, re-import into n8n.
 *
 *   npm run build:workflow
 *
 * The pipeline is deliberately one node per responsibility rather than one
 * giant Code node: opening the workflow in n8n should show the architecture.
 *
 *   Webhook
 *     → Authenticate            shared-secret check
 *     → Validate input          shape, size, types
 *     → Normalise & parse       control chars, turn array, roster
 *     → Build Gemini request    system prompt + JSON schema + user prompt
 *     → Gemini (HTTP)           structured JSON output
 *     → Parse & schema-validate unwrap, JSON.parse, contract check
 *     → Verify evidence         every quote matched against the transcript
 *     → KPI engine              deterministic talk-ratio / word / question stats
 *     → Quality gate            coverage / grounding / support scoring
 *     → Format response         { analysis, quality, diagnostics }
 *     → Respond
 */

